create table if not exists public.assets (
  id text primary key check (length(id) between 1 and 40),
  name text not null check (length(name) between 1 and 160),
  category text not null default '기타',
  location text not null default '',
  status text not null default 'available' check (status in ('available','maintenance')),
  note text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.loans (
  id bigint generated by default as identity primary key,
  asset_id text not null references public.assets(id) on update cascade,
  borrower_name text not null check (length(trim(borrower_name)) between 1 and 100),
  borrowed_at date not null default current_date,
  due_date date not null,
  returned_at date,
  memo text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (due_date >= borrowed_at),
  check (returned_at is null or returned_at >= borrowed_at)
);
create index if not exists loans_asset_active_idx on public.loans(asset_id) where returned_at is null;
create index if not exists loans_borrowed_at_idx on public.loans(borrowed_at desc);
alter table public.assets enable row level security;
alter table public.loans enable row level security;
drop policy if exists "Anyone can read assets" on public.assets;
create policy "Anyone can read assets" on public.assets for select to anon, authenticated using (true);
drop policy if exists "Admins manage assets" on public.assets;
create policy "Admins manage assets" on public.assets for all to authenticated using (true) with check (true);
drop policy if exists "Anyone can read loans" on public.loans;
create policy "Anyone can read loans" on public.loans for select to anon, authenticated using (true);
drop policy if exists "Anyone can create loan records" on public.loans;
create policy "Anyone can create loan records" on public.loans for insert to anon, authenticated with check (returned_at is null and length(trim(borrower_name)) between 1 and 100);
drop policy if exists "Admins update loans" on public.loans;
create policy "Admins update loans" on public.loans for update to authenticated using (true) with check (true);
drop policy if exists "Admins delete loans" on public.loans;
create policy "Admins delete loans" on public.loans for delete to authenticated using (true);
-- Prevent simultaneous active loans for the same item, including concurrent requests.
create or replace function public.prevent_duplicate_active_loan()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.returned_at is null and exists (
    select 1 from public.loans l where l.asset_id = new.asset_id and l.returned_at is null and l.id <> coalesce(new.id, -1)
  ) then raise exception '이 비품은 이미 대여 중입니다.'; end if;
  return new;
end; $$;
drop trigger if exists loans_prevent_duplicate_active on public.loans;
create trigger loans_prevent_duplicate_active before insert or update on public.loans for each row execute function public.prevent_duplicate_active_loan();
