create table if not exists public.consumables (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) between 1 and 160),
  category text not null default '기타',
  unit text not null default '개',
  quantity numeric(12,2) not null default 0 check (quantity >= 0),
  min_quantity numeric(12,2) not null default 1 check (min_quantity >= 0),
  location text not null default '',
  note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.reorder_requests (
  id bigint generated by default as identity primary key,
  consumable_id uuid not null references public.consumables(id) on delete cascade,
  requested_quantity numeric(12,2) not null check (requested_quantity > 0),
  requester text not null check (length(trim(requester)) between 1 and 100),
  note text not null default '',
  status text not null default 'pending' check (status in ('pending','ordered','received')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists consumables_name_idx on public.consumables(name);
create index if not exists reorder_requests_status_created_idx on public.reorder_requests(status, created_at desc);

alter table public.consumables enable row level security;
alter table public.reorder_requests enable row level security;

grant select on public.consumables to anon, authenticated;
grant insert, update, delete on public.consumables to authenticated;
grant select, insert on public.reorder_requests to anon, authenticated;
grant update, delete on public.reorder_requests to authenticated;
grant usage, select on sequence public.reorder_requests_id_seq to anon, authenticated;

drop policy if exists consumables_public_read on public.consumables;
drop policy if exists consumables_admin_manage on public.consumables;
drop policy if exists reorder_requests_public_read on public.reorder_requests;
drop policy if exists reorder_requests_public_create on public.reorder_requests;
drop policy if exists reorder_requests_admin_update on public.reorder_requests;
drop policy if exists reorder_requests_admin_delete on public.reorder_requests;

create policy consumables_public_read
on public.consumables for select to anon, authenticated
using (true);

create policy consumables_admin_manage
on public.consumables for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

create policy reorder_requests_public_read
on public.reorder_requests for select to anon, authenticated
using (true);

create policy reorder_requests_public_create
on public.reorder_requests for insert to anon, authenticated
with check (true);

create policy reorder_requests_admin_update
on public.reorder_requests for update to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

create policy reorder_requests_admin_delete
on public.reorder_requests for delete to authenticated
using ((select public.is_admin()));


-- 사용/입고 이력과 원자적 재고 증감 함수
create table if not exists public.consumable_movements (
  id bigint generated by default as identity primary key,
  consumable_id uuid not null references public.consumables(id) on delete cascade,
  movement_type text not null check (movement_type in ('use','in')),
  quantity numeric(12,2) not null check (quantity > 0),
  actor text not null check (length(trim(actor)) between 1 and 100),
  note text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists consumable_movements_created_idx on public.consumable_movements(created_at desc);
create index if not exists consumable_movements_item_idx on public.consumable_movements(consumable_id, created_at desc);

alter table public.consumable_movements enable row level security;
grant select on public.consumable_movements to anon, authenticated;
grant usage, select on sequence public.consumable_movements_id_seq to anon, authenticated;
drop policy if exists consumable_movements_public_read on public.consumable_movements;
create policy consumable_movements_public_read on public.consumable_movements for select to anon, authenticated using (true);
revoke insert, update, delete on public.consumable_movements from anon, authenticated;

create or replace function public.record_consumable_movement(
  p_consumable_id uuid,
  p_movement_type text,
  p_quantity numeric,
  p_actor text,
  p_note text default ''
) returns public.consumable_movements
language plpgsql security definer set search_path = public
as $$
declare
  item public.consumables%rowtype;
  movement public.consumable_movements%rowtype;
  next_quantity numeric(12,2);
begin
  if p_movement_type not in ('use','in') then raise exception '유효하지 않은 재고 변동 유형입니다.'; end if;
  if p_quantity is null or p_quantity <= 0 then raise exception '수량은 0보다 커야 합니다.'; end if;
  if p_actor is null or length(trim(p_actor)) = 0 then raise exception '기록자를 입력하세요.'; end if;
  select * into item from public.consumables where id = p_consumable_id for update;
  if not found then raise exception '소모품을 찾을 수 없습니다.'; end if;
  next_quantity := case when p_movement_type = 'in' then item.quantity + p_quantity else item.quantity - p_quantity end;
  if next_quantity < 0 then raise exception '현재 재고보다 많은 수량을 차감할 수 없습니다. 현재 재고: %', item.quantity; end if;
  update public.consumables set quantity = next_quantity, updated_at = now() where id = p_consumable_id;
  insert into public.consumable_movements(consumable_id,movement_type,quantity,actor,note)
  values(p_consumable_id,p_movement_type,p_quantity,trim(p_actor),coalesce(p_note,'')) returning * into movement;
  return movement;
end;
$$;
revoke all on function public.record_consumable_movement(uuid,text,numeric,text,text) from public;
grant execute on function public.record_consumable_movement(uuid,text,numeric,text,text) to anon, authenticated;
